def get_face_name(face_id: int | str) -> str:
    """获取 QQ 表情名称。

    Args:
        face_id: 表情 ID。

    Returns:
        表情中文名称，若未收录则返回通用标识。
    """
    try:
        fid = int(face_id)
        if fid in QQ_FACE_MAP:
            return QQ_FACE_MAP[fid]
        return f"表情_{fid}"
    except (ValueError, TypeError):
        return f"表情_{face_id}"
